"""Create and enforce opaque per-session Gradio artifact directories."""

from __future__ import annotations

import os
import re
import secrets
import stat
import time
from pathlib import Path

_SCOPE_PATTERN = re.compile(r"^[A-Za-z0-9_-]{43}$")
_PROJECT_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_RESULTS_DIR = os.path.join(_PROJECT_ROOT, "gradio_outputs").replace("\\", "/")
SESSION_RESULTS_DIR = os.path.join(DEFAULT_RESULTS_DIR, "sessions").replace("\\", "/")


class SessionArtifactAccessError(ValueError):
    """Raised when a path or scope crosses a Gradio session boundary."""


def create_session_artifact_scope() -> str:
    """Return a cryptographically random opaque scope for one page session."""

    return secrets.token_urlsafe(32)


def resolve_session_artifact_scope(scope: object | None) -> str:
    """Validate a scope token/state or create one for compatibility callers."""

    if scope is None:
        return create_session_artifact_scope()
    if not isinstance(scope, str):
        scope = getattr(scope, "token", None)
    if not isinstance(scope, str) or _SCOPE_PATTERN.fullmatch(scope) is None:
        raise SessionArtifactAccessError("Invalid session artifact scope")
    return scope


def session_artifact_root(scope: str, *, create: bool = False) -> str:
    """Return the canonical directory owned by ``scope``.

    Args:
        scope: Opaque session capability generated by this module.
        create: Create the managed root when it does not yet exist.

    Raises:
        SessionArtifactAccessError: If a managed directory is unsafe.
    """

    token = resolve_session_artifact_scope(scope)
    if create:
        _ensure_managed_directory(DEFAULT_RESULTS_DIR)
        _ensure_managed_directory(SESSION_RESULTS_DIR)
    else:
        for managed_dir in (DEFAULT_RESULTS_DIR, SESSION_RESULTS_DIR):
            if os.path.lexists(managed_dir):
                _assert_directory_without_symlink(managed_dir)

    if os.path.lexists(SESSION_RESULTS_DIR):
        results_real = os.path.realpath(DEFAULT_RESULTS_DIR)
        sessions_real = os.path.realpath(SESSION_RESULTS_DIR)
        if not _contains(sessions_real, results_real):
            raise SessionArtifactAccessError("Session output root escaped generated outputs")

    root = os.path.abspath(os.path.join(SESSION_RESULTS_DIR, token))
    if not _contains(root, os.path.abspath(SESSION_RESULTS_DIR)):
        raise SessionArtifactAccessError("Session artifact root escaped its parent")

    if create:
        try:
            os.mkdir(root, mode=0o700)
        except FileExistsError:
            pass

    if os.path.lexists(root):
        _assert_directory_without_symlink(root)
        parent_real = os.path.realpath(SESSION_RESULTS_DIR)
        root_real = os.path.realpath(root)
        if not _contains(root_real, parent_real):
            raise SessionArtifactAccessError("Session artifact root resolved outside its parent")
        return root_real.replace("\\", "/")

    return root.replace("\\", "/")


def allocate_session_batch_directory(scope: str | None) -> tuple[str, str]:
    """Create a collision-resistant batch directory and return ``(scope, path)``."""

    active_scope = resolve_session_artifact_scope(scope)
    root = session_artifact_root(active_scope, create=True)
    for _ in range(8):
        suffix = secrets.token_hex(8)
        name = f"batch_{time.time_ns()}_{suffix}"
        batch_dir = os.path.join(root, name)
        try:
            os.mkdir(batch_dir, mode=0o700)
        except FileExistsError:
            continue
        authorized = authorize_session_artifact_path(
            batch_dir,
            active_scope,
            must_exist=True,
        )
        return active_scope, authorized
    raise SessionArtifactAccessError("Could not allocate a unique session batch directory")


def is_managed_artifact_path(path: str | os.PathLike[str]) -> bool:
    """Return whether a path is inside the application's generated-output tree."""

    raw = _absolute(path)
    resolved = os.path.realpath(raw)
    return _contains(raw, os.path.abspath(DEFAULT_RESULTS_DIR)) or _contains(
        resolved,
        os.path.realpath(DEFAULT_RESULTS_DIR),
    )


def authorize_session_artifact_path(
    path: str | os.PathLike[str],
    scope: str | None,
    *,
    must_exist: bool = True,
) -> str:
    """Authorize a managed path only when it belongs to ``scope``.

    Paths outside ``gradio_outputs`` are returned canonically and remain subject
    to their caller's normal trust policy. Managed output paths require both
    lexical and resolved containment beneath the current opaque session root.
    """

    raw = _absolute(path)
    resolved = os.path.realpath(raw)
    if not is_managed_artifact_path(raw):
        return resolved.replace("\\", "/")

    active_scope = resolve_session_artifact_scope(scope)
    root = session_artifact_root(active_scope, create=False)
    root_raw = os.path.abspath(root)
    root_real = os.path.realpath(root)
    if not os.path.isdir(root_real):
        raise SessionArtifactAccessError("Current session artifact root does not exist")
    if not _contains(raw, root_raw) or not _contains(resolved, root_real):
        raise SessionArtifactAccessError("Generated artifact belongs to another session")

    _assert_no_symlink_components(root_raw, raw)
    if must_exist and not os.path.exists(resolved):
        raise SessionArtifactAccessError("Generated artifact does not exist")
    return resolved.replace("\\", "/")


def _ensure_managed_directory(path: str) -> None:
    """Create a managed directory and reject symlink or non-directory entries."""

    os.makedirs(path, mode=0o700, exist_ok=True)
    _assert_directory_without_symlink(path)


def _stat_is_link_or_reparse(info: os.stat_result) -> bool:
    """Recognize POSIX symlinks and Windows reparse points without following them."""

    if stat.S_ISLNK(info.st_mode):
        return True
    attributes = getattr(info, "st_file_attributes", 0)
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0)
    return bool(reparse_flag and attributes & reparse_flag)


def _assert_directory_without_symlink(path: str) -> None:
    """Require ``path`` to be a real directory rather than a link/reparse point."""

    try:
        info = os.lstat(path)
    except OSError as exc:
        raise SessionArtifactAccessError(f"Cannot inspect managed directory: {path}") from exc
    if _stat_is_link_or_reparse(info) or not stat.S_ISDIR(info.st_mode):
        raise SessionArtifactAccessError(f"Unsafe managed directory: {path}")


def _assert_no_symlink_components(root: str, path: str) -> None:
    """Reject link or reparse-point components between the root and target."""

    relative = os.path.relpath(path, root)
    if relative == os.pardir or relative.startswith(os.pardir + os.sep):
        raise SessionArtifactAccessError("Artifact path escaped its session root")
    current = root
    for part in Path(relative).parts:
        current = os.path.join(current, part)
        if not os.path.lexists(current):
            break
        try:
            info = os.lstat(current)
        except OSError as exc:
            raise SessionArtifactAccessError(
                f"Cannot inspect managed artifact component: {current}"
            ) from exc
        if _stat_is_link_or_reparse(info):
            raise SessionArtifactAccessError(
                "Links and reparse points are not allowed in session artifacts"
            )


def _absolute(path: str | os.PathLike[str]) -> str:
    """Return an expanded absolute path without following symlinks."""

    return os.path.abspath(os.path.expanduser(os.fspath(path)))


def _contains(path: str, root: str) -> bool:
    """Return whether ``path`` is equal to or nested beneath ``root``."""

    normalized_path = os.path.normcase(os.path.normpath(path))
    normalized_root = os.path.normcase(os.path.normpath(root))
    try:
        return os.path.commonpath([normalized_path, normalized_root]) == normalized_root
    except ValueError:
        return False
